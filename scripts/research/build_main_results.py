#!/usr/bin/env python3
"""
Build main-results artifacts from available experiment outputs.

Outputs:
- JSON summary
- CSV summary table
- TeX snippet for quick inclusion in paper draft
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path


def _load_json(path: Path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _load_qa_records(raw_qa: Path, qa_chunks_dir: Path) -> tuple[list[dict], str]:
    records: list[dict] = []
    source = "none"

    if raw_qa.exists():
        data = _load_json(raw_qa)
        if isinstance(data, list) and len(data) > 0:
            records = [x for x in data if isinstance(x, dict)]
            source = "raw_qa_pairs"
            return records, source

    if qa_chunks_dir.exists():
        for p in sorted(qa_chunks_dir.glob("*.json")):
            try:
                data = _load_json(p)
            except Exception:
                continue
            if isinstance(data, list):
                records.extend(x for x in data if isinstance(x, dict))
            elif isinstance(data, dict):
                records.append(data)
        if records:
            source = "qa_chunks_fallback"

    return records, source


def _intrinsic_from_records(records: list[dict]) -> dict:
    if not records:
        return {
            "n_records": 0,
            "parse_valid_rate": 0.0,
            "duplicate_rate": 0.0,
            "diversity_ratio": 0.0,
            "multimodal_ratio": 0.0,
            "bloom_distribution": {},
        }

    required = {"qa_id", "question_content", "candidate_answers", "ground_truth", "legal_rationale"}
    valid = 0
    sig = Counter()
    qset = set()
    bloom = Counter()
    mm = 0

    for r in records:
        keys = set(r.keys())
        if required.issubset(keys) and str(r.get("question_content", "")).strip():
            valid += 1
        q = " ".join(str(r.get("question_content", "")).lower().split())
        gt = " ".join(str(r.get("ground_truth", "")).lower().split())
        sig[(q, gt)] += 1
        qset.add(q)
        bloom[str(r.get("bloom_level", "Unknown"))] += 1
        if bool(r.get("is_multimodal", False)):
            mm += 1

    dup = sum(v - 1 for v in sig.values() if v > 1)
    return {
        "n_records": len(records),
        "parse_valid_rate": valid / len(records),
        "duplicate_rate": dup / len(records),
        "diversity_ratio": len(qset) / len(records),
        "multimodal_ratio": mm / len(records),
        "bloom_distribution": dict(bloom),
    }


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def _to_pct(x: float) -> str:
    return f"{x*100:.2f}\\%"


def _build_tex_snippet(summary: dict) -> str:
    split = summary["split_summary"]
    gates = summary["quality_gates"]
    intrinsic = summary["intrinsic_primary"]

    def s(name: str, key: str):
        return split.get(name, {}).get(key, 0)

    lines = []
    lines.append("% Auto-generated by scripts/research/build_main_results.py")
    lines.append("\\newcommand{\\SplitTrainDocs}{" + str(s("train", "n_docs")) + "}")
    lines.append("\\newcommand{\\SplitTrainCtx}{" + str(s("train", "n_contexts")) + "}")
    lines.append("\\newcommand{\\SplitDevDocs}{" + str(s("dev", "n_docs")) + "}")
    lines.append("\\newcommand{\\SplitDevCtx}{" + str(s("dev", "n_contexts")) + "}")
    lines.append("\\newcommand{\\SplitTestDocs}{" + str(s("test", "n_docs")) + "}")
    lines.append("\\newcommand{\\SplitTestCtx}{" + str(s("test", "n_contexts")) + "}")
    lines.append("\\newcommand{\\GateA}{" + _to_pct(gates.get("gate_a_ocr_chunk_coverage", 0.0)) + "}")
    lines.append("\\newcommand{\\GateB}{" + _to_pct(gates.get("gate_b_valid_context_ratio", 0.0)) + "}")
    lines.append("\\newcommand{\\GateC}{" + _to_pct(gates.get("gate_c_parse_valid_qa_ratio", 0.0)) + "}")
    lines.append("\\newcommand{\\GateD}{" + _to_pct(gates.get("gate_d_duplicate_qa_rate", 0.0)) + "}")
    lines.append("\\newcommand{\\PrimaryN}{" + str(intrinsic.get("n_records", 0)) + "}")
    lines.append("\\newcommand{\\PrimaryParseValid}{" + _to_pct(intrinsic.get("parse_valid_rate", 0.0)) + "}")
    lines.append("\\newcommand{\\PrimaryDupRate}{" + _to_pct(intrinsic.get("duplicate_rate", 0.0)) + "}")
    lines.append("\\newcommand{\\PrimaryDiversity}{" + _to_pct(intrinsic.get("diversity_ratio", 0.0)) + "}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Build main results summary artifacts.")
    parser.add_argument("--split-json", type=Path, required=True)
    parser.add_argument("--quality-gates-json", type=Path, required=True)
    parser.add_argument("--raw-qa", type=Path, required=True)
    parser.add_argument("--qa-chunks-dir", type=Path, required=True)
    parser.add_argument("--out-json", type=Path, required=True)
    parser.add_argument("--out-csv", type=Path, required=True)
    parser.add_argument("--out-tex", type=Path, required=True)
    args = parser.parse_args()

    split = _load_json(args.split_json)
    qg = _load_json(args.quality_gates_json)
    records, source = _load_qa_records(args.raw_qa, args.qa_chunks_dir)
    intrinsic = _intrinsic_from_records(records)

    summary = {
        "split_summary": split.get("summary", {}),
        "quality_gates": qg.get("gates", {}),
        "qa_source_for_intrinsic": source,
        "intrinsic_primary": intrinsic,
    }

    rows = [
        {
            "system": "Primary(current)",
            "n_records": intrinsic["n_records"],
            "parse_valid_rate": intrinsic["parse_valid_rate"],
            "duplicate_rate": intrinsic["duplicate_rate"],
            "diversity_ratio": intrinsic["diversity_ratio"],
            "multimodal_ratio": intrinsic["multimodal_ratio"],
            "qa_source": source,
        }
    ]

    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out_json, "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    _write_csv(args.out_csv, rows)
    tex = _build_tex_snippet(summary)
    args.out_tex.parent.mkdir(parents=True, exist_ok=True)
    with open(args.out_tex, "w", encoding="utf-8") as f:
        f.write(tex)

    print(f"[OK] JSON: {args.out_json}")
    print(f"[OK] CSV : {args.out_csv}")
    print(f"[OK] TeX : {args.out_tex}")
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()

