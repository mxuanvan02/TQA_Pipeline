#!/usr/bin/env python3
"""
Aggregate benchmark JSON reports into CSV and TeX summary tables.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def _load_json(path: Path) -> dict:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _pct(x: float | None) -> str:
    if x is None:
        return "--"
    return f"{x * 100:.2f}%"


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _model_label(report: dict) -> str:
    return str(report.get("model_id", "unknown")).split("/")[-1]


def aggregate(report_dir: Path) -> tuple[list[dict], list[dict], list[dict]]:
    reports = []
    for path in sorted(report_dir.glob("bench_*.json")):
        report = _load_json(path)
        report["_path"] = path
        reports.append(report)

    grouped: dict[tuple[str, str], dict[str, dict]] = {}
    for report in reports:
        model = _model_label(report)
        split = str(report.get("split") or "all")
        key = (model, split)
        grouped.setdefault(key, {})
        mode = "noctx" if bool(report.get("no_context")) else "ctx"
        grouped[key][mode] = report

    main_rows: list[dict] = []
    bloom_rows: list[dict] = []
    modality_rows: list[dict] = []

    for (model, split), pair in sorted(grouped.items()):
        ctx = pair.get("ctx")
        noctx = pair.get("noctx")

        ctx_acc = ctx.get("metrics", {}).get("accuracy_overall") if ctx else None
        noctx_acc = noctx.get("metrics", {}).get("accuracy_overall") if noctx else None
        delta = (ctx_acc - noctx_acc) if ctx_acc is not None and noctx_acc is not None else None
        n_samples = ctx.get("n_samples") if ctx else (noctx.get("n_samples") if noctx else 0)

        main_rows.append(
            {
                "model": model,
                "split": split,
                "n_samples": n_samples,
                "acc_ctx": _pct(ctx_acc),
                "acc_noctx": _pct(noctx_acc),
                "delta_ctx_minus_noctx": _pct(delta) if delta is not None else "--",
                "ctx_report": ctx["_path"].name if ctx else "",
                "noctx_report": noctx["_path"].name if noctx else "",
            }
        )

        for setting_name, report in (("ctx", ctx), ("noctx", noctx)):
            if not report:
                continue
            metrics = report.get("metrics", {})
            by_bloom = metrics.get("by_bloom", {})
            by_modality = metrics.get("by_modality", {})
            bloom_rows.append(
                {
                    "model": model,
                    "split": split,
                    "setting": setting_name,
                    "remember": _pct(by_bloom.get("Remember")),
                    "understand": _pct(by_bloom.get("Understand")),
                    "apply": _pct(by_bloom.get("Apply")),
                }
            )
            modality_rows.append(
                {
                    "model": model,
                    "split": split,
                    "setting": setting_name,
                    "text_only": _pct(by_modality.get("text_only")),
                    "multimodal": _pct(by_modality.get("multimodal")),
                }
            )

    return main_rows, bloom_rows, modality_rows


def build_tex(main_rows: list[dict]) -> str:
    lines = [
        "% Auto-generated by scripts/research/build_benchmark_tables.py",
        "% Paste the table below into Section 6 after benchmark runs complete.",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Zero-shot benchmark results on the eval-ready test split.}",
        "\\label{tab:main_benchmark}",
        "\\begin{tabular}{lccc}",
        "\\toprule",
        "\\textbf{Model} & \\textbf{N} & \\textbf{Acc. (ctx)} & \\textbf{Acc. (no-ctx)} \\\\",
        "\\midrule",
    ]
    for row in main_rows:
        if row["split"] != "test":
            continue
        lines.append(
            f"{row['model']} & {row['n_samples']} & {row['acc_ctx']} & {row['acc_noctx']} \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Aggregate benchmark reports into tables.")
    parser.add_argument("--report-dir", type=Path, required=True)
    parser.add_argument("--out-main-csv", type=Path, required=True)
    parser.add_argument("--out-bloom-csv", type=Path, required=True)
    parser.add_argument("--out-modality-csv", type=Path, required=True)
    parser.add_argument("--out-tex", type=Path, required=True)
    args = parser.parse_args()

    main_rows, bloom_rows, modality_rows = aggregate(args.report_dir)
    _write_csv(args.out_main_csv, main_rows)
    _write_csv(args.out_bloom_csv, bloom_rows)
    _write_csv(args.out_modality_csv, modality_rows)
    args.out_tex.parent.mkdir(parents=True, exist_ok=True)
    args.out_tex.write_text(build_tex(main_rows), encoding="utf-8")

    print(f"[OK] Main CSV     : {args.out_main_csv}")
    print(f"[OK] Bloom CSV    : {args.out_bloom_csv}")
    print(f"[OK] Modality CSV : {args.out_modality_csv}")
    print(f"[OK] TeX snippet  : {args.out_tex}")


if __name__ == "__main__":
    main()
